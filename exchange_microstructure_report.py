def inject(report: str) -> None:
    if not LATEST_REPORT.exists():
        atomic_text(LATEST_REPORT, f"{START_MARKER}\n{report.rstrip()}\n{END_MARKER}\n")
        return
    old = LATEST_REPORT.read_text(encoding="utf-8")
    block = f"{START_MARKER}\n{report.rstrip()}\n{END_MARKER}"
    if START_MARKER in old and END_MARKER in old:
        pattern = re.compile(re.escape(START_MARKER) + r".*?" + re.escape(END_MARKER), re.DOTALL)
        new = pattern.sub(block, old, count=1)
    else:
        anchor = "<!-- EXCHANGE_SIGNAL_TRACKER_START -->"
        if anchor in old:
            new = old.replace(anchor, block + "\n\n" + anchor, 1)
        else:
            anchor = "<!-- LIQUIDATION_SUMMARY_START -->"
            if anchor in old:
                new = old.replace(anchor, block + "\n\n" + anchor, 1)
            else:
                anchor = "<!-- TECHNICAL_STRUCTURE_START -->"
                new = old.replace(anchor, block + "\n\n" + anchor, 1) if anchor in old else old.rstrip() + "\n\n" + block + "\n"
    atomic_text(LATEST_REPORT, new)


def main() -> None:
    snapshot = read_json(SNAPSHOT_PATH)
    assets_payload = snapshot.get("assets", {}) if isinstance(snapshot, dict) else {}
    if not isinstance(assets_payload, dict) or not assets_payload:
        raise SystemExit(f"Snapshot exchange mancante o vuoto: {SNAPSHOT_PATH}")

    health = read_json(HEALTH_PATH)
    storage = read_json(STORAGE_STATUS_PATH)
    tech = technical_rows()
    scanner = scanner_rows()
    tracker = tracker_30d_rows()
    tracker_7d = tracker_7d_rows()
    intraday = intraday_summaries()

    metrics: list[dict[str, Any]] = []
    for asset in ASSETS:
        asset_row = assets_payload.get(asset, {})
        if not isinstance(asset_row, dict):
            asset_row = {}
        asset_row = enrich_asset_with_intraday(asset_row, intraday.get(asset, {}))
        metric = score_asset(asset, asset_row, tech.get(asset, {}), tracker_7d.get(asset, {}))
        metric["source_health"] = safe_text(health.get("status"), "n/a")
        for exchange in ("binance", "bybit", "kucoin"):
            metric[f"{exchange}_status"] = exchange_health_status(health, asset, exchange)
        metrics.append(metric)

    overlays = [
        prediction_overlay(asset, next(row for row in metrics if row["asset"] == asset), scanner.get(asset, {}), tracker.get(asset, {}))
        for asset in ASSETS
    ]

    write_csv(METRICS_PATH, metrics, METRIC_FIELDS)
    write_csv(PREDICTION_PATH, overlays, PREDICTION_FIELDS)
    history = update_history(metrics, overlays)
    charts = make_history_charts(history)
    report = render_report(
        metrics,
        overlays,
        health,
        charts,
        safe_int(snapshot.get("liquidation_sample_seconds"), 0),
        storage,
    )
    atomic_text(REPORT_PATH, report)
    atomic_text(DIAGNOSTICS_PATH, render_source_diagnostics(health, storage))
    inject(report)

    print(f"Exchange microstructure report scritto in: {REPORT_PATH}")
    print(f"Diagnostica fonti scritta in: {DIAGNOSTICS_PATH}")
    print(f"Metriche exchange scritte in: {METRICS_PATH}")
    print(f"History exchange scritta in: {HISTORY_PATH}")
    print(f"Overlay previsione scritto in: {PREDICTION_PATH}")
    for row in metrics:
        print(
            f"{row['asset']}: raw {fmt_score(row['raw_score'])} | candidato {fmt_int_score(row['candidate_global_score'])} | "
            f"Global {fmt_int_score(row['global_score'])} | {row['bias']} | {row['confidence']}"
        )


if __name__ == "__main__":
    main()
