def utc_now_iso() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def utc_now_text() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")


def utc_date() -> str:
    return datetime.now(timezone.utc).date().isoformat()


def safe_float(value: Any, default: float | None = None) -> float | None:
    try:
        number = float(value)
        return number if math.isfinite(number) else default
    except (TypeError, ValueError):
        return default


def safe_int(value: Any, default: int = 0) -> int:
    number = safe_float(value)
    return int(number) if number is not None else default


def safe_text(value: Any, default: str = "") -> str:
    if value is None:
        return default
    text = str(value).strip()
    return text if text and text.lower() not in {"nan", "none", "null"} else default


def clamp(value: float, low: float, high: float) -> float:
    return max(low, min(high, value))


def read_json(path: Path) -> dict[str, Any]:
    if not path.exists():
        return {}
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
        return payload if isinstance(payload, dict) else {}
    except Exception:
        return {}


def read_csv_rows(path: Path) -> list[dict[str, str]]:
    if not path.exists():
        return []
    try:
        with path.open("r", encoding="utf-8", newline="") as handle:
            return list(csv.DictReader(handle))
    except Exception:
        return []


def atomic_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(text, encoding="utf-8", newline="\n")
    tmp.replace(path)


def write_csv(path: Path, rows: list[dict[str, Any]], fieldnames: list[str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    with tmp.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=fieldnames, extrasaction="ignore")
        writer.writeheader()
        for row in rows:
            writer.writerow({field: row.get(field, "") for field in fieldnames})
    tmp.replace(path)


def normalize_asset(value: Any) -> str:
    return safe_text(value).upper().replace("-USD", "").replace("USDT", "")



def parse_utc_datetime(value: Any) -> datetime | None:
    text = safe_text(value).replace("Z", "+00:00")
    if not text:
        return None
    try:
        parsed = datetime.fromisoformat(text)
        if parsed.tzinfo is None:
            parsed = parsed.replace(tzinfo=timezone.utc)
        return parsed.astimezone(timezone.utc)
    except ValueError:
        return None


def average_values(rows: list[dict[str, Any]], key: str) -> float | None:
    values = [safe_float(row.get(key)) for row in rows]
    values = [value for value in values if value is not None]
    return sum(values) / len(values) if values else None


def sum_values(rows: list[dict[str, Any]], key: str) -> float:
    return sum(value for value in (safe_float(row.get(key)) for row in rows) if value is not None)


def period_change(rows: list[dict[str, Any]], key: str, minimum_span_hours: float) -> float | None:
    if len(rows) < 2:
        return None
    first = safe_float(rows[0].get(key))
    last = safe_float(rows[-1].get(key))
    first_time = parse_utc_datetime(rows[0].get("timestamp_utc"))
    last_time = parse_utc_datetime(rows[-1].get("timestamp_utc"))
    if first in (None, 0) or last is None or first_time is None or last_time is None:
        return None
    if (last_time - first_time).total_seconds() < minimum_span_hours * 3600:
        return None
    return (last / first - 1.0) * 100.0


def intraday_summaries() -> dict[str, dict[str, Any]]:
    rows = read_csv_rows(INTRADAY_PATH)
    parsed: list[dict[str, Any]] = []
    for row in rows:
        timestamp = parse_utc_datetime(row.get("timestamp_utc"))
        asset = normalize_asset(row.get("asset"))
        if timestamp is None or asset not in ASSETS:
            continue
        item = dict(row)
        item["_timestamp"] = timestamp
        item["asset"] = asset
        parsed.append(item)
    if not parsed:
        return {}

    latest_time = max(row["_timestamp"] for row in parsed)
    output: dict[str, dict[str, Any]] = {}
    for asset in ASSETS:
        asset_rows = sorted((row for row in parsed if row["asset"] == asset), key=lambda row: row["_timestamp"])
        if not asset_rows:
            continue
        rows_24h = [row for row in asset_rows if row["_timestamp"] >= latest_time - timedelta(hours=24)]
        rows_4h = [row for row in asset_rows if row["_timestamp"] >= latest_time - timedelta(hours=4)]
        span_hours = (asset_rows[-1]["_timestamp"] - asset_rows[0]["_timestamp"]).total_seconds() / 3600
        output[asset] = {
            "intraday_samples_4h": len(rows_4h),
            "intraday_samples_24h": len(rows_24h),
            "intraday_span_hours": span_hours,
            "intraday_taker_ratio_avg_4h": average_values(rows_4h, "taker_buy_sell_ratio_4h"),
            "intraday_taker_ratio_avg_24h": average_values(rows_24h, "taker_buy_sell_ratio_4h"),
            "intraday_book_imbalance_avg_4h": average_values(rows_4h, "orderbook_imbalance_0_5pct"),
            "intraday_book_imbalance_avg_24h": average_values(rows_24h, "orderbook_imbalance_0_5pct"),
            "intraday_funding_avg_24h": average_values(rows_24h, "funding_rate_pct"),
            "intraday_oi_change_4h_pct": period_change(rows_4h, "open_interest_usd_combined", 2.5),
            "intraday_oi_change_24h_pct": period_change(rows_24h, "open_interest_usd_combined", 18.0),
            "intraday_price_change_4h_pct": period_change(rows_4h, "price", 2.5),
            "intraday_price_change_24h_pct": period_change(rows_24h, "price", 18.0),
            "intraday_long_liquidation_usd_observed_24h": sum_values(rows_24h, "long_liquidation_usd_sample"),
            "intraday_short_liquidation_usd_observed_24h": sum_values(rows_24h, "short_liquidation_usd_sample"),
            "intraday_liquidation_events_observed_24h": sum_values(rows_24h, "liquidation_events_sample"),
        }
    return output


def enrich_asset_with_intraday(asset_row: dict[str, Any], summary: dict[str, Any]) -> dict[str, Any]:
    row = dict(asset_row)
    if not summary:
        row["_intraday"] = {}
        return row
    row["_intraday"] = summary
    if safe_int(summary.get("intraday_samples_4h"), 0) >= 3:
        for target, source in (
            ("taker_buy_sell_ratio_4h", "intraday_taker_ratio_avg_4h"),
            ("orderbook_imbalance_0_5pct", "intraday_book_imbalance_avg_4h"),
            ("oi_change_4h_pct", "intraday_oi_change_4h_pct"),
        ):
            value = safe_float(summary.get(source))
            if value is not None:
                row[target] = value
    if safe_int(summary.get("intraday_samples_24h"), 0) >= 8:
        for target, source in (
            ("taker_buy_sell_ratio_24h", "intraday_taker_ratio_avg_24h"),
            ("funding_rate_pct", "intraday_funding_avg_24h"),
            ("oi_change_24h_pct", "intraday_oi_change_24h_pct"),
            ("price_change_24h_pct", "intraday_price_change_24h_pct"),
        ):
            value = safe_float(summary.get(source))
            if value is not None:
                row[target] = value
        liq = dict(row.get("liquidation_sample", {})) if isinstance(row.get("liquidation_sample"), dict) else {}
        liq["long_liquidation_usd"] = summary.get("intraday_long_liquidation_usd_observed_24h")
        liq["short_liquidation_usd"] = summary.get("intraday_short_liquidation_usd_observed_24h")
        liq["events"] = summary.get("intraday_liquidation_events_observed_24h")
        row["liquidation_sample"] = liq
    return row

