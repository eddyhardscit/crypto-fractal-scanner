    fib_positive_states = {"TENUTO", "RECUPERATO", "RECLAIMED", "HELD"}
    fib_negative_states = {"PERSO", "RESPINTO", "LOST", "REJECTED"}
    if not fib_state:
        fib_confirmation = "Fibonacci strutturato non disponibile."
