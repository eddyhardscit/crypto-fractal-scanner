def liquidity_wall_summary(row: dict[str, Any], price: float | None) -> tuple[str, str]:
    bid_candidates: list[tuple[str, dict[str, Any]]] = []
    ask_candidates: list[tuple[str, dict[str, Any]]] = []
    for exchange in ("binance", "bybit", "kucoin"):
        bid = row.get(f"{exchange}_bid_wall")
        ask = row.get(f"{exchange}_ask_wall")
        if isinstance(bid, dict) and safe_float(bid.get("notional")) is not None:
            bid_candidates.append((exchange, bid))
        if isinstance(ask, dict) and safe_float(ask.get("notional")) is not None:
            ask_candidates.append((exchange, ask))

    def describe(candidates: list[tuple[str, dict[str, Any]]], label: str) -> str:
        if not candidates:
            return f"{label}: n/a"
        exchange, wall = max(candidates, key=lambda item: safe_float(item[1].get("notional"), 0.0) or 0.0)
        wall_price = safe_float(wall.get("price"))
        notional = safe_float(wall.get("notional"))
        distance = safe_float(wall.get("distance_pct"))
        multiple = safe_float(wall.get("multiple_median"))
        return (
            f"{label} {exchange} @ {fmt_price_raw(wall_price)} "
            f"({fmt_pct(distance)}, {fmt_usd(notional)}, {multiple:.1f}x mediana)"
            if multiple is not None
            else f"{label} {exchange} @ {fmt_price_raw(wall_price)} ({fmt_pct(distance)}, {fmt_usd(notional)})"
        )

    return describe(bid_candidates, "muro bid"), describe(ask_candidates, "muro ask")


def prediction_overlay(
    asset: str,
    exchange_metric: dict[str, Any],
    scanner: dict[str, str],
    tracker: dict[str, str],
) -> dict[str, Any]:
    raw_positive = safe_float(scanner.get("positive_cases_30d"))
    raw_return = safe_float(scanner.get("return_p50_pct"))
    controls = safe_int(tracker.get("controls"), 0)
    accuracy = safe_float(tracker.get("accuracy_direction_pct"))
    exchange_score = safe_int(exchange_metric.get("candidate_global_score"), 0)

    weight = 0.0
    status = "RACCOLTA DATI"
    note = "Overlay non attivo: servono almeno 30 controlli maturati a 30 giorni."
    if controls >= 30 and accuracy is not None:
        if accuracy >= 55.0:
            # 55% -> 0.25, 70%+ -> 1.0. This is deliberately conservative.
            weight = clamp((accuracy - 50.0) / 20.0, 0.0, 1.0)
            status = "ATTIVO / CALIBRATO"
            note = "L'overlay usa soltanto l'affidabilità osservata del modulo exchange."
        elif accuracy < 45.0:
            status = "SOSPESO / MODULO DEBOLE"
            note = "Accuratezza exchange sotto 45%: nessun aggiustamento automatico."
        else:
            status = "NEUTRO / VANTAGGIO NON DIMOSTRATO"
            note = "Campione sufficiente, ma accuratezza troppo vicina al caso."

    adjusted_positive = raw_positive
    adjusted_return = raw_return
    if raw_positive is not None and exchange_score and weight > 0:
        adjusted_positive = clamp(raw_positive + exchange_score * 5.0 * weight, 1.0, 99.0)
    if raw_return is not None and exchange_score and weight > 0:
        adjusted_return = raw_return + exchange_score * 1.5 * weight

    return {
        "generated_utc": utc_now_iso(),
        "asset": asset,
        "raw_positive_rate_30d": raw_positive,
        "raw_return_p50_30d": raw_return,
        "exchange_score": exchange_score,
        "tracker_controls_30d": controls,
        "tracker_accuracy_30d": accuracy,
        "overlay_status": status,
        "overlay_weight": round(weight, 4),
        "adjusted_positive_rate_30d": adjusted_positive,
        "adjusted_return_p50_30d": adjusted_return,
        "note": note,
    }


